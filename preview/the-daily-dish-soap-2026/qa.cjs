'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const zlib=require('node:zlib');
const root=__dirname;
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const botanicalsText=fs.readFileSync(path.join(root,'botanicals.js'),'utf8');
const materialsText=fs.readFileSync(path.join(root,'materials.js'),'utf8');
let count=0;
function ok(value,message){assert.ok(value,message);count++}
const context={window:{}};
new vm.Script(botanicalsText,{filename:'botanicals.js'}).runInNewContext(context);
const bot=context.window.TDS_BOTANICAL_PREVIEW;
ok(Array.isArray(bot)&&bot.length===50,'Exactly 50 botanical records');
ok(bot.every(x=>x.name&&x.latin&&x.category),'All botanical identity fields');
ok(bot.every(x=>Array.isArray(x.pros)&&x.pros.length>0),'Every botanical has pros');
ok(bot.every(x=>Array.isArray(x.cons)&&x.cons.length>0),'Every botanical has cons');
ok(bot.every(x=>x.color&&x.colorName&&/^#[0-9a-f]{6}$/i.test(x.colorHex)),'Every botanical has color context');
ok(bot.every(x=>x.scent||x.aroma),'Every botanical has aroma information');
ok(bot.every(x=>x.caution&&x.testSuggested),'Every botanical has precautions and trial proposal');
ok(!bot.some(x=>x.image),'Do not auto-load photos lacking individually certified rights');
new vm.Script(materialsText,{filename:'materials.js'});
const b64=materialsText.match(/atob\("([A-Za-z0-9+/=]+)"\)/)?.[1];
ok(!!b64,'Compressed materials payload exists');
const mat=JSON.parse(zlib.inflateSync(Buffer.from(b64,'base64')).toString('utf8'));
ok(mat.length===50,'Exactly 50 functional ingredients');
ok(mat.every(x=>x.name&&x.family&&x.inciDraft),'Materials identity and draft INCI');
ok(mat.every(x=>x.role&&x.focus&&x.checks),'Materials role, limitations and checks');
ok(html.includes('botanicals.js')&&html.includes('materials.js'),'Both original datasets loaded');
const sections=['inicio','materias','funcionales','comparar','colores','aromas','cuaderno','rigor'];
for(const section of sections){ok(html.includes('id="'+section+'"'),'Section '+section);}
ok(html.includes('b.pros')&&html.includes('b.cons')&&html.includes('b.caution')&&html.includes('b.color'),'Rich profiles rendered');
ok(html.includes('renderMaterialCards')&&html.includes('renderColorAndAroma'),'Catalogs rendered');
ok(!/service_role|sk_live_|api_key|@gmail\.com|supabase\.co/.test(html+materialsText+botanicalsText),'No credentials or other projects endpoints');
ok(html.includes('noindex,nofollow'),'Do not index unlisted demo');
ok(html.includes('No se presentan como instrucciones de fabricación'),'Safety notes retained');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(v=>v.trim());
ok(scripts.length>0,'Inline UI script');
for(const [i,source] of scripts.entries())new vm.Script(source,{filename:'inline-'+i+'.js'});
ok(!html.includes('window.TDS_CLOUD')&&!html.includes('localStorage'),'No real cloud client or persistent shared data');
console.log('TDS_DEMO_100_PROFILES_QA=PASS ('+count+' assertions)');
